USE FEBJAVA;

CREATE TABLE Account (
AccountID INT PRIMARY KEY AUTO_INCREMENT,
AccountHolderName VARCHAR(100) NOT NULL, Balance DECIMAL(10,2) NOT NULL DEFAULT 0.00
);

INSERT INTO Account (AccountHolderName, Balance) 
