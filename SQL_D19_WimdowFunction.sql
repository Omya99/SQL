-- Windows Functions
-- COMAPNY
CREATE TABLE COMPANY(ID INT, NAME VARCHAR(30), SALARY INT);
INSERT INTO COMPANY(ID,NAME,SALARY)
VALUES(1,"A",50000),(2,"B",40000),(3,"C",40000),(4,"D",20000);
SELECT * FROM COMPANY;

SELECT NAME,SALARY,
ROW_NUMBER() OVER (ORDER BY SALARY DESC) AS ROW_NUM,
RANK() OVER (ORDER BY SALARY DESC) AS RANK_VAL,
DENSE_RANK() OVER (ORDER BY SALARY DESC) AS DENSE
FROM COMPANY;

-- EMPLOYEE1
