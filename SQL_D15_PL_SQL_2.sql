-- Section 3: Aggregate Functions & Filtering
-- •	Create a stored procedure to list employees whose salary is greater than the average salary of all employees.
DELIMITER $$
CREATE PROCEDURE GREATER_AVG_SALARY()
BEGIN
SELECT * FROM EMPLOYEE1 WHERE SALARY>(SELECT AVG(SALARY) FROM EMPLOYEE1);
END $$
DELIMITER ;
CALL GREATER_AVG_SALARY();

-- •	Write a stored procedure that returns the highest salary in the entire employees table.
DELIMITER $$
CREATE PROCEDURE MAX_SALARY()
BEGIN
SELECT * FROM EMPLOYEE1 WHERE SALARY=(SELECT MAX(SALARY) FROM EMPLOYEE1);
END $$
DELIMITER ;
CALL MAX_SALARY();

