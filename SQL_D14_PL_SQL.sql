-- no-parameter Questions ->

-- Get Employee with Salary > 70000
DELIMITER $$
CREATE PROCEDURE GETEMPLOYEE_SALARY1()
SELECT * FROM EMPLOYEE1 WHERE SALARY>70000;
END $$
DELIMITER ;
CALL GETEMPLOYEE_SALARY1();

-- Count Total Employees
DELIMITER $$
CREATE PROCEDURE COUNT_EMPLOYEE()
BEGIN
SELECT COUNT(*) FROM EMPLOYEE1;
END $$
DELIMITER ;
CALL COUNT_EMPLOYEE();

-- List employees Hired after 2020
DELIMITER $$
CREATE PROCEDURE HIRED_AFTER_2020()
SELECT * FROM EMPLOYEE1 WHERE YEAR(HIRE_DATE)>2020;
END $$
DELIMITER ;
CALL HIRED_AFTER_2020()

-- Show Top 5 Highest Paid Employees
DELIMITER $$
CREATE PROCEDURE HIGHEST_PAID_EMP()
BEGIN 
SELECT * FROM EMPLOYEE1 ORDER BY SALARY DESC LIMIT 5;
END $$
DELIMITER ;
CALL HIGHEST_PAID_EMP();


