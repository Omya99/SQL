-- QUESTIONS SUBQUERY ->
-- 1️) Subquery in WHERE (Students older than average age)
SELECT STUDENT_NAME,AGE FROM STUDENTS2 
WHERE AGE > (SELECT AVG(AGE) FROM STUDENTS2);

-- 2️) Students from the same city as 'Rahul'
SELECT STUDENT_NAME, CITY FROM STUDENTS2
WHERE CITY=(SELECT CITY FROM STUDENTS2 WHERE STUDENT_NAME="Rahul");

-- 3️) Students with maximum age
SELECT STUDENT_NAME, AGE FROM STUDENTS2
WHERE AGE = (SELECT MAX(AGE) FROM STUDENTS2);

-- 4️) Students studying the same course as 'Neha'
SELECT STUDENT_NAME,COURSE FROM STUDENTS2 
WHERE COURSE=(SELECT COURSE FROM STUDENTS2 WHERE STUDENT_NAME="NEHA");

-- 5️) Students whose age is equal to minimum age
SELECT STUDENT_NAME, AGE FROM STUDENTS2
WHERE AGE=(SELECT MIN(AGE) FROM STUDENTS2);

-- 6️) Subquery with IN (Students from cities that have BCA students)
SELECT STUDENT_NAME, CITY, COURSE FROM STUDENTS2
WHERE CITY IN(SELECT CITY FROM STUDENTS2 WHERE COURSE="BCA");


