SELECT * FROM PRODUCT2;
-- 1. Find products whose price is greater than the average price.
SELECT PRODUCTNAME FROM PRODUCT2 
WHERE PRICE > (SELECT AVG(PRICE) FROM PRODUCT2);

-- 2. Find the most expensive product.
SELECT PRODUCTNAME FROM PRODUCT2 
WHERE PRICE = (SELECT MAX(PRICE)FROM PRODUCT2);

-- 3. Find the cheapest product.
SELECT * FROM PRODUCT2
WHERE PRICE = (SELECT MIN(PRICE) FROM PRODUCT2);

-- 4. Find products having stock greater than average stock.
SELECT PRODUCTNAME FROM PRODUCT2 
WHERE QUANTITYINSTOCK > (SELECT AVG(QUANTITYINSTOCK) FROM PRODUCT2);

-- 5. Find products from the same category as Smartphone.
SELECT PRODUCTNAME FROM PRODUCT2
WHERE CATEGORY = (SELECT CATEGORY FROM PRODUCT2 WHERE PRODUCTNAME='SMARTPHONE');

-- 6. Find products costing more than the price of Keyboard.
SELECT PRODUCTNAME,PRICE FROM PRODUCT2
WHERE PRICE > (SELECT PRICE FROM PRODUCT2 WHERE PRODUCTNAME="KEYBOARD");

-- 7. Find products with stock less than the stock of Smartphone.
SELECT PRODUCTNAME, QUANTITYINSTOCK FROM PRODUCT2 
WHERE QUANTITYINSTOCK < (SELECT QUANTITYINSTOCK FROM PRODUCT2 WHERE PRODUCTNAME="SMARTPHONE");

-- 8. Find the second most expensive product.
SELECT PRODUCTNAME,PRICE FROM PRODUCT2 
WHERE PRICE=(SELECT MAX(PRICE) FROM PRODUCT2
WHERE PRICE<(SELECT MAX(PRICE) FROM PRODUCT2));

-- 9. Find categories having more than one product.
SELECT CATEGORY,COUNT(CATEGORY) FROM PRODUCT2
GROUP BY CATEGORY HAVING COUNT(*)>1;

-- 10. Find products belonging to categories whose average price is above ₹5000. 
